CREATE TABLE parking_spots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(20) NOT NULL,
    occupancy_status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    in_maintenance BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_parking_spots_code UNIQUE (code),
    CONSTRAINT ck_parking_spots_vehicle_type
        CHECK (vehicle_type IN ('MOTORBIKE', 'CAR')),
    CONSTRAINT ck_parking_spots_occupancy_status
        CHECK (occupancy_status IN ('AVAILABLE', 'OCCUPIED'))
);

CREATE INDEX idx_parking_spots_lookup
    ON parking_spots (vehicle_type, occupancy_status, in_maintenance, code);

CREATE TABLE parking_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(20) NOT NULL,
    parking_spot_id BIGINT NOT NULL,
    check_in_time TIMESTAMP WITH TIME ZONE NOT NULL,
    check_out_time TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_parking_sessions_spot
        FOREIGN KEY (parking_spot_id) REFERENCES parking_spots (id),
    CONSTRAINT ck_parking_sessions_vehicle_type
        CHECK (vehicle_type IN ('MOTORBIKE', 'CAR')),
    CONSTRAINT ck_parking_sessions_status
        CHECK (status IN ('ACTIVE', 'COMPLETED')),
    CONSTRAINT ck_parking_sessions_timeline
        CHECK (check_out_time IS NULL OR check_out_time >= check_in_time),
    CONSTRAINT ck_parking_sessions_completion
        CHECK (
            (status = 'ACTIVE' AND check_out_time IS NULL)
            OR (status = 'COMPLETED' AND check_out_time IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uq_parking_sessions_active_license_plate
    ON parking_sessions (license_plate)
    WHERE status = 'ACTIVE';

CREATE UNIQUE INDEX uq_parking_sessions_active_spot
    ON parking_sessions (parking_spot_id)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_parking_sessions_check_in
    ON parking_sessions (check_in_time DESC, id DESC);

CREATE INDEX idx_parking_sessions_status
    ON parking_sessions (status);

CREATE TABLE gate_events (
    event_id VARCHAR(64) PRIMARY KEY,
    gate_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    processing_status VARCHAR(20) NOT NULL,
    response_data JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_gate_events_event_type
        CHECK (event_type IN ('ENTRY', 'EXIT')),
    CONSTRAINT ck_gate_events_processing_status
        CHECK (processing_status IN ('PROCESSING', 'SUCCEEDED', 'REJECTED'))
);

CREATE INDEX idx_gate_events_created_at
    ON gate_events (created_at DESC);

CREATE TABLE admin_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_admin_accounts_username_not_blank
        CHECK (BTRIM(username) <> ''),
    CONSTRAINT ck_admin_accounts_password_hash_not_blank
        CHECK (BTRIM(password_hash) <> '')
);

CREATE UNIQUE INDEX uq_admin_accounts_username_ci
    ON admin_accounts (LOWER(username));
